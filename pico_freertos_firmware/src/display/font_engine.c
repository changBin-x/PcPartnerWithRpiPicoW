static const AssetBlob* s_font_blob = NULL;
static bool s_ready = false;
static uint32_t s_cn_codepoints[kFontCnGlyphCount];

/* 解码一个 UTF-8 码点并前移游标；非法序列消费 1 字节并返回 0。 */
static int utf8_next(const char** cursor, uint32_t* out_codepoint) {
  const unsigned char* bytes = (const unsigned char*)*cursor;
  const unsigned char first = bytes[0];
  int length = 0;
  uint32_t codepoint = 0;
  if (first < 0x80u) {
    codepoint = first;
    length = 1;
  } else if ((first & 0xe0u) == 0xc0u) {
    codepoint = first & 0x1fu;
    length = 2;
  } else if ((first & 0xf0u) == 0xe0u) {
    codepoint = first & 0x0fu;
    length = 3;
  } else if ((first & 0xf8u) == 0xf0u) {
    codepoint = first & 0x07u;
    length = 4;
  } else {
    *cursor += 1;
    *out_codepoint = 0xfffdu;
    return 0;
  }
  for (int index = 1; index < length; ++index) {
    const unsigned char byte = bytes[index];
    if ((byte & 0xc0u) != 0x80u) {
      *cursor += 1;
      *out_codepoint = 0xfffdu;
      return 0;
    }
    codepoint = (codepoint << 6) | (byte & 0x3fu);
  }
  *cursor += length;
  *out_codepoint = codepoint;
  return length;
}

static int chinese_index(uint32_t codepoint) {
  for (int index = 0; index < kFontCnGlyphCount; ++index) {
    if (s_cn_codepoints[index] == codepoint) {
      return index;
    }
  }
  return -1;
}

static const uint8_t* ascii_glyph(char symbol) {
  unsigned int code = (unsigned char)symbol;
  if (code < 0x20u || code > 0x7au) {
    code = (unsigned int)'?';
  }
  unsigned int index = code - 0x20u;
  if (kAsciiPresent[index] == 0u) {
    index = (unsigned int)'?' - 0x20u;
  }
  return kAsciiFont[index];
}

static const uint8_t* chinese_glyph_for_codepoint(uint32_t codepoint) {
  const int index = chinese_index(codepoint);
  if (index < 0) {
    return NULL;
  }
  return s_font_blob->data + (size_t)index * (size_t)kFontChineseBytes;
}

bool font_engine_init(const AssetBlob* blob) {
  s_ready = false;
  if (blob == NULL || blob->data == NULL) {
    return false;
  }
  if (blob->size != (size_t)kFontCnGlyphCount * (size_t)kFontChineseBytes) {
    return false;
  }

  const char* cursor = kFontCnOrder;
  int count = 0;
  while (*cursor != '\0' && count < kFontCnGlyphCount) {
    uint32_t codepoint = 0;
    if (utf8_next(&cursor, &codepoint) == 0) {
      return false;
    }
    s_cn_codepoints[count] = codepoint;
    ++count;
  }
  if (*cursor != '\0' || count != kFontCnGlyphCount) {
    return false;
  }

  s_font_blob = blob;
  s_ready = true;
  return true;
}

bool font_engine_is_ready(void) { return s_ready; }

const uint8_t* font_engine_ascii_glyph(char symbol) {
  if (!s_ready) {
    return NULL;
  }
  return ascii_glyph(symbol);
}

const uint8_t* font_engine_chinese_glyph(const char* utf8_symbol) {
  if (!s_ready || utf8_symbol == NULL) {
    return NULL;
  }
  const char* cursor = utf8_symbol;
  uint32_t codepoint = 0;
  utf8_next(&cursor, &codepoint);
  return chinese_glyph_for_codepoint(codepoint);
}

int font_engine_text_width(const char* text) {
  if (!s_ready || text == NULL) {
    return 0;
  }
  int width = 0;
  const char* cursor = text;
  while (*cursor != '\0') {
    if ((unsigned char)*cursor < 0x80u) {
      width += kFontAsciiWidth;
      ++cursor;
    } else {
      uint32_t codepoint = 0;
      utf8_next(&cursor, &codepoint);
      width += kFontChineseWidth;
    }
  }
  return width;
}

int font_engine_clock_text_width(const char* text) {
  if (!s_ready || text == NULL) {
    return 0;
  }
  int width = 0;
  for (const char* cursor = text; *cursor != '\0'; ++cursor) {
    if (*cursor == ':') {
      width += kFontClockColonAdvance;
    } else if (*cursor >= '0' && *cursor <= '9') {
      width += kFontClockDigitAdvance;
    } else {
      width += kFontAsciiWidth;
    }
  }
  return width;
}

uint16_t font_engine_blend_rgb565(uint16_t foreground, uint16_t background,
                                  uint8_t coverage) {
  if (coverage == 0u) {
    return background;
  }
  if (coverage >= 15u) {
    return foreground;
  }
  const uint32_t weight = coverage;
  const uint32_t inverse = 15u - weight;
  const uint32_t foreground_red = (foreground >> 11) & 0x1fu;
  const uint32_t foreground_green = (foreground >> 5) & 0x3fu;
  const uint32_t foreground_blue = foreground & 0x1fu;
  const uint32_t background_red = (background >> 11) & 0x1fu;
  const uint32_t background_green = (background >> 5) & 0x3fu;
  const uint32_t background_blue = background & 0x1fu;
  const uint32_t red =
      (foreground_red * weight + background_red * inverse + 7u) / 15u;
  const uint32_t green =
      (foreground_green * weight + background_green * inverse + 7u) / 15u;
  const uint32_t blue =
      (foreground_blue * weight + background_blue * inverse + 7u) / 15u;
  return (uint16_t)((red << 11) | (green << 5) | blue);
}

void font_engine_draw_glyph(const FontSurface* surface, int x, int y,
                            const uint8_t* glyph, int glyph_width,
                            int glyph_height, uint16_t color,
                            uint16_t background_color) {
  if (surface == NULL || surface->pixels == NULL || glyph == NULL) {
    return;
  }
  if (glyph_width <= 0 || glyph_height <= 0) {
    return;
  }

  int first_row = 0;
  if (y < surface->origin_y) {
    first_row = surface->origin_y - y;
  }
  int last_row = glyph_height;
  const int surface_bottom = surface->origin_y + surface->height;
  if (y + last_row > surface_bottom) {
    last_row = surface_bottom - y;
  }
  if (first_row >= last_row) {
    return;
  }

  int first_column = x < 0 ? -x : 0;
  int last_column = glyph_width;
  if (x + last_column > surface->width) {
    last_column = surface->width - x;
  }
  if (first_column >= last_column) {
    return;
  }

  for (int row = first_row; row < last_row; ++row) {
    uint16_t* destination =
        surface->pixels +
        (size_t)(y + row - surface->origin_y) * (size_t)surface->width;
    for (int column = first_column; column < last_column; ++column) {
      const size_t pixel_index =
          (size_t)row * (size_t)glyph_width + (size_t)column;
      const uint8_t packed = glyph[pixel_index >> 1];
      const uint8_t coverage =
          (pixel_index & 1u) != 0u ? (packed & 0x0fu) : (packed >> 4);
      destination[x + column] =
          font_engine_blend_rgb565(color, background_color, coverage);
    }
  }
}

int font_engine_draw_text(const FontSurface* surface, int x, int y,
                          const char* text, uint16_t color,
                          uint16_t background_color) {
  if (!s_ready || surface == NULL || surface->pixels == NULL || text == NULL) {
    return 0;
  }
  int advance = 0;
  const char* cursor = text;
  while (*cursor != '\0') {
    const uint8_t* glyph = NULL;
    int glyph_width = kFontAsciiWidth;
    int glyph_height = kFontAsciiHeight;
    if ((unsigned char)*cursor < 0x80u) {
      glyph = ascii_glyph(*cursor);
      ++cursor;
    } else {
      uint32_t codepoint = 0;
      utf8_next(&cursor, &codepoint);
      glyph = chinese_glyph_for_codepoint(codepoint);
      if (glyph == NULL) {
        glyph = kChinesePlaceholder;
      }
      glyph_width = kFontChineseWidth;
      glyph_height = kFontChineseHeight;
    }
    font_engine_draw_glyph(surface, x + advance, y, glyph, glyph_width,
                           glyph_height, color, background_color);
    advance += glyph_width;
  }
  return advance;
}

int font_engine_draw_clock_text(const FontSurface* surface, int x, int y,
                                const char* text, uint16_t color,
                                uint16_t background_color) {
  if (!s_ready || surface == NULL || surface->pixels == NULL || text == NULL) {
    return 0;
  }
  int advance = 0;
  for (const char* cursor = text; *cursor != '\0'; ++cursor) {
    const uint8_t* glyph = NULL;
    int glyph_width = kFontAsciiWidth;
    int glyph_height = kFontAsciiHeight;
    int step = kFontAsciiWidth;
    if (*cursor == ':') {
      glyph = kClockColon;
      glyph_width = kFontClockColonWidth;
      glyph_height = kFontClockColonHeight;
      step = kFontClockColonAdvance;
    } else if (*cursor >= '0' && *cursor <= '9') {
      glyph = kClockDigits[*cursor - '0'];
      glyph_width = kFontClockDigitWidth;
      glyph_height = kFontClockDigitHeight;
      step = kFontClockDigitAdvance;
    } else {
      glyph = ascii_glyph(*cursor);
    }
    font_engine_draw_glyph(surface, x + advance, y, glyph, glyph_width,
                           glyph_height, color, background_color);
    advance += step;
  }
  return advance;
}
